-- Additive Phase 4A. Apply after 001-004. No existing tracking rows are rewritten.
begin;
create table public.game_tracking (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id) on delete cascade,
 igdb_id integer not null check(igdb_id>0),
 status text check(status in ('playing','completed','backlog','paused','dropped')),
 owned boolean,
 platform_ids integer[] not null default '{}',
 manual_playtime_minutes integer check(manual_playtime_minutes between 0 and 6000000),
 progress numeric(5,2) check(progress between 0 and 100),
 started_on date,completed_on date,last_played_on date,
 rating numeric check(rating between 0.5 and 5 and rating*2=trunc(rating*2)),
 review text not null default '' check(char_length(review)<=10000),
 contains_spoilers boolean not null default false,
 wishlist boolean not null default false,to_be_played boolean not null default false,want_to_play_more boolean not null default false,favorite boolean not null default false,
 created_at timestamptz not null default now(),updated_at timestamptz not null default now(),
 unique(user_id,igdb_id),
 check(started_on is null or completed_on is null or started_on<=completed_on),
 check(started_on is null or last_played_on is null or started_on<=last_played_on)
);
create index game_tracking_recent on public.game_tracking(user_id,updated_at desc,igdb_id);
create index game_tracking_status on public.game_tracking(user_id,status,completed_on desc);
alter table public.game_tracking enable row level security;
revoke all on public.game_tracking from public,anon,authenticated;
grant select,delete on public.game_tracking to authenticated;
grant insert(user_id,igdb_id,status,owned,platform_ids,manual_playtime_minutes,progress,started_on,completed_on,last_played_on,rating,review,contains_spoilers,wishlist,to_be_played,want_to_play_more,favorite),
 update(user_id,igdb_id,status,owned,platform_ids,manual_playtime_minutes,progress,started_on,completed_on,last_played_on,rating,review,contains_spoilers,wishlist,to_be_played,want_to_play_more,favorite) on public.game_tracking to authenticated;
create policy "Owner reads games" on public.game_tracking for select to authenticated using(user_id=(select auth.uid()));
create policy "Owner inserts games" on public.game_tracking for insert to authenticated with check(user_id=(select auth.uid()));
create policy "Owner updates games" on public.game_tracking for update to authenticated using(user_id=(select auth.uid())) with check(user_id=(select auth.uid()));
create policy "Owner deletes games" on public.game_tracking for delete to authenticated using(user_id=(select auth.uid()));
create function public.validate_game_tracking() returns trigger language plpgsql set search_path='' as $$
begin
 if tg_op='UPDATE' and (new.user_id<>old.user_id or new.igdb_id<>old.igdb_id) then raise exception 'Game identity cannot change' using errcode='23514'; end if;
 if cardinality(new.platform_ids)>50 or array_position(new.platform_ids,null) is not null or exists(select 1 from unnest(new.platform_ids) p where p<=0) or cardinality(new.platform_ids)<>(select count(distinct p) from unnest(new.platform_ids) p) then raise exception 'Invalid platform selection' using errcode='23514'; end if;
 if new.started_on>(now() at time zone 'UTC')::date or new.completed_on>(now() at time zone 'UTC')::date or new.last_played_on>(now() at time zone 'UTC')::date then raise exception 'Future game date' using errcode='23514'; end if;
 new.updated_at=now();return new;
end;
$$;
revoke all on function public.validate_game_tracking() from public,anon,authenticated;
create trigger validate_game_tracking before insert or update on public.game_tracking for each row execute function public.validate_game_tracking();
-- Keep the existing list identities and URLs. tmdb_id remains the legacy movie/TV
-- identity column; game entries use a separate igdb_id with exclusive constraints.
alter table public.media_lists add column description text not null default '' check(char_length(description)<=2000);
grant select(description) on public.media_lists to anon;
grant insert(description),update(description) on public.media_lists to authenticated;
alter table public.media_list_items add column igdb_id integer check(igdb_id>0);
alter table public.media_list_items add column position bigint generated by default as identity;
alter table public.media_list_items drop constraint media_list_items_pkey;
alter table public.media_list_items alter column tmdb_id drop not null;
alter table public.media_list_items drop constraint media_list_items_media_type_check;
alter table public.media_list_items add constraint media_list_items_media_type_check check(media_type in ('movie','tv','game'));
alter table public.media_list_items add constraint media_list_identity check((media_type='game' and igdb_id is not null and tmdb_id is null) or (media_type in ('movie','tv') and tmdb_id is not null and igdb_id is null));
create unique index media_list_tmdb_identity on public.media_list_items(list_id,media_type,tmdb_id) where tmdb_id is not null;
create unique index media_list_igdb_identity on public.media_list_items(list_id,igdb_id) where igdb_id is not null;
grant insert(igdb_id) on public.media_list_items to authenticated;
-- Reordering is atomic and owner-scoped; callers cannot supply arbitrary SQL.
create function public.move_media_list_item(p_list uuid,p_type text,p_id integer,p_direction integer) returns void language plpgsql security definer set search_path='' as $$
declare current_position bigint; other_position bigint; other_type text; other_id integer;
begin
 if (select auth.uid()) is null or not exists(select 1 from public.media_lists where id=p_list and user_id=(select auth.uid())) then raise exception 'List owner required' using errcode='42501'; end if;
 if p_direction is null or p_direction not in (-1,1) or p_type is null or p_type not in ('movie','tv','game') or p_id is null or p_id<=0 then raise exception 'Invalid list movement' using errcode='22023'; end if;
 perform 1 from public.media_lists where id=p_list for update;
 select position into current_position from public.media_list_items where list_id=p_list and media_type=p_type and coalesce(igdb_id,tmdb_id)=p_id;
 if current_position is null then return; end if;
 select position,media_type,coalesce(igdb_id,tmdb_id) into other_position,other_type,other_id from public.media_list_items
 where list_id=p_list and (case when p_direction=-1 then position<current_position else position>current_position end)
 order by (case when p_direction=-1 then -position else position end) asc limit 1;
 if other_position is null then return; end if;
 update public.media_list_items set position=other_position where list_id=p_list and media_type=p_type and coalesce(igdb_id,tmdb_id)=p_id;
 update public.media_list_items set position=current_position where list_id=p_list and media_type=other_type and coalesce(igdb_id,tmdb_id)=other_id;
end;
$$;
revoke all on function public.move_media_list_item(uuid,text,integer,integer) from public,anon,authenticated;
grant execute on function public.move_media_list_item(uuid,text,integer,integer) to authenticated;
commit;
