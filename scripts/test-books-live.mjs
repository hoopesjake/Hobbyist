// Read-only real Open Library verification. No Supabase writes or login required.
import {mkdir,writeFile} from "node:fs/promises";
import {pathToFileURL} from "node:url";
import path from "node:path";
process.loadEnvFile(".env.local");
const {build}=await import(pathToFileURL(path.resolve("node_modules/.cache/calendar-tools/node_modules/esbuild/lib/main.js")).href);
await mkdir(".next/books-verification",{recursive:true});
const output=path.resolve(".next/books-verification/live-catalog.cjs");
await build({entryPoints:["src/lib/open-library.ts"],outfile:output,bundle:true,platform:"node",format:"cjs",plugins:[{name:"server-cache-stubs",setup(plugin){plugin.onResolve({filter:/^(server-only|next\/cache)$/},args=>({path:args.path,namespace:"stubs"}));plugin.onLoad({filter:/.*/,namespace:"stubs"},args=>({contents:args.path==="next/cache"?"export function cacheLife(){}":"export {};"}));}}]});
const catalog=(await import(pathToFileURL(output).href)).default;
const redRising=await catalog.searchBooks("red rising");
if(redRising.books[0]?.title!=="Red Rising" || !redRising.books[0]?.authors.includes("Pierce Brown"))throw Error("Red Rising by Pierce Brown must be the first title match");
if(redRising.books.some(book=>book.title==="Bible"))throw Error("Unrelated Bible result in title search");
console.log('Red Rising title search passed: first result is Red Rising by Pierce Brown; no unrelated Bible result.');
const redDetails=await catalog.getBook(redRising.books[0].id);
if(!redRising.books[0].cover_url || redDetails.cover_url!==redRising.books[0].cover_url)throw Error('Search/detail English edition covers must match');
console.log('Red Rising English edition cover:',redDetails.cover_url);
if(!redDetails.default_edition_id)throw Error('Open Library preferred edition not supplied');
const defaultEdition=await catalog.getBookEdition(redDetails.id,redDetails.default_edition_id);
console.log('Red Rising default edition:',defaultEdition.id,'pages:',defaultEdition.pages);
const subjectRecords=await catalog.getBookSubjects([redDetails.id,15358691]);
if(subjectRecords.length!==2 || !subjectRecords.some(book=>book.subjects.length))throw Error('Batch book subjects unavailable');
console.log('Live genre metadata returned for',subjectRecords.length,'books.');
const search=await catalog.searchBooks("The Way of Kings");
const match=search.books.find(book=>book.title==="The Way of Kings"&&book.authors.includes("Brandon Sanderson"));
if(!match)throw Error("Expected real title/author not returned");
const book=await catalog.getBook(match.id),editions=await catalog.getBookEditions(match.id);
if(!book.title||!book.authors.includes("Brandon Sanderson")||!editions.editions.length)throw Error("Book/author/edition details not returned");
const edition=await catalog.getBookEdition(book.id,editions.editions[0].id);
const cover=book.cover_url?await fetch(book.cover_url,{method:"HEAD",signal:AbortSignal.timeout(12000)}):null;
const report={searchReturned:search.books.length,id:book.work_key,title:book.title,authors:book.authors,descriptionPresent:!!book.description,edition:edition.id,editionPages:edition.pages,coverStatus:cover?.status||null,coverType:cover?.headers.get("content-type")||null};
console.log(JSON.stringify(report,null,2));
await writeFile(".next/books-verification/live-result.json",JSON.stringify(report,null,2));
